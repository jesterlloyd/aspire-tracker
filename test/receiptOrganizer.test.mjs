test('the filed list is the year’s accepted receipts with the rows they posted, read live', async () => {
  const pg = new PGlite()
  await pg.exec(read('test/fixtures/budgetReceiptsPrelude.sql'))
  const { rows: [owner] } = await pg.query(`INSERT INTO user_profiles (full_name, email, role, is_owner) VALUES ('Jester Lloyd Bautista', 'j@x.org', 'owner', true) RETURNING *`)
  for (const m of ['20261009000000_program_budget_phase_a', '20261010000000_budget_subscription_approval', '20261011000000_budget_subscription_cells', '20261012000000_budget_expense_zero_quantity', '20261013000000_budget_receipts'])
    await pg.exec(runnable(read(`supabase/migrations/${m}.sql`)))
  await pg.exec(runnable(read('db/migrations/seed_program_budget_fy26.sql')))
  const db = pgliteRest(pg)
  await E.startYear(db, owner, { fy: 2027, total: 40000, cost_center: 'Nursing Education', plan: 'none', today: TODAY })
  await pg.query(`UPDATE keith_skills SET status = 'active', enabled = true, version = 1 WHERE slug = 'read-receipt'`)
  const reading = { vendor: 'Amazon', order_number: '112-7730158-4402217', date: '2026-09-03', card_last4: '', subtotal: 53.49, tax: 0, shipping: 0, tip: 0, total: 53.49, has_shipping_address: true, unreadable_fields: [],
    lines: [{ item: 'Copy Paper', quantity: 1, amount: 38.99, category: 'Printing & Copying', confidence: 'high', reason: 'Paper.' }, { item: 'Name Badge Labels', quantity: 2, amount: 14.5, category: 'Supplies & Materials', confidence: 'high', reason: 'Labels.' }] }
  const { receipt, upload } = await R.startUpload(db, owner, { fileName: 'a.jpg', contentType: 'image/jpeg', size: 3 })
  await db.storage.from(R.RECEIPT_BUCKET).upload(upload.path, Buffer.from('abc'))
  const read1 = await R.readReceipt(db, owner, { id: receipt.id, complete: async () => ({ ok: true, text: JSON.stringify(reading), model: 'm', usage: {} }), today: TODAY })
  const acc = await R.acceptReceipt(db, owner, { id: receipt.id, draft: { ...read1.receipt.draft, payment_method: 'personal_concur' }, today: TODAY })
  const [filed] = await R.filedReceipts(db, { fy: 2027, today: TODAY })
  assert.deepEqual([filed.vendor, filed.total, filed.items, filed.decided_by, filed.filed_name], ['Amazon', 53.49, ['Copy Paper', 'Name Badge Labels'], 'Jester Lloyd Bautista', acc.filed_name])
  assert.deepEqual(filed.rows.map(r => [r.row_label, r.category, r.amount, r.statusLabel, r.payment]), [
    ['FY27 row 1', 'Printing & Copying', 38.99, 'Recorded', 'Personal (Concur)'], ['FY27 row 2', 'Supplies & Materials', 14.5, 'Recorded', 'Personal (Concur)']])
  assert.deepEqual(await R.filedReceipts(db, { fy: 2026, today: TODAY }), [], 'a year holds only its own receipts')
  // A row changed in the Sheet shows its change here; a deleted one drops out.
  await E.updateExpense(db, owner, { id: filed.rows[0].id, patch: { status: 'submitted' }, today: TODAY })
  await E.deleteExpenses(db, owner, { ids: [filed.rows[1].id] })
  const [again] = await R.filedReceipts(db, { fy: 2027, today: TODAY })
  assert.deepEqual(again.rows.map(r => r.statusLabel), ['Submitted'])
})


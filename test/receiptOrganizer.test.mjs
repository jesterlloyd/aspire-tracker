test('Filed groups by month newest first, and a split receipt counts in each category for what it spent there', () => {
  const months = M.filedFolders([R1, R2, R3, R4], { groupBy: 'month' })
  assert.deepEqual(months.map(f => [f.key, f.count, f.total]), [['September 2026', 2, 549.82], ['July 2026', 1, 350], ['December 2025', 1, 20]])
  assert.deepEqual(months[0].entries.map(e => e.receipt.id), ['b', 'a'], 'newest first inside a folder')
  const cats = M.filedFolders([R1, R2, R3], { groupBy: 'category' })
  assert.deepEqual(cats.map(f => [f.key, f.count, f.total]), [['Meals & Catering', 1, 496.33], ['Printing & Copying', 1, 38.99], ['Supplies & Materials', 2, 364.5]])
  assert.equal(cats.find(f => f.key === 'Printing & Copying').entries[0].part, 38.99)
  assert.equal(cats.find(f => f.key === 'Meals & Catering').entries[0].part, null, 'a single-category receipt is not split')
  const sum = cats.reduce((a, f) => a + f.total, 0)
  assert.equal(Math.round(sum * 100), Math.round((R1.total + R2.total + R3.total) * 100), 'the category folders add up to the receipts')
  assert.deepEqual(M.filedFolders([R1, R2, R3], { groupBy: 'vendor' }).map(f => [f.key, f.count]), [['Amazon', 2], ['Beverly Grove Catering', 1]])
  // BUDGET-FIXES-1 release 2 changed this: Filed groups by Stage, the Sheet's one word (was Status).
  assert.deepEqual(M.filedFolders([R1, R2, R3], { groupBy: 'status' }).map(f => f.key), ['Receipt attached', 'Reimbursed or Paid', 'Submitted to Concur'])
  assert.deepEqual(M.filedFolders([R1, R2, R3], { query: 'notebook' }).map(f => f.entries.map(e => e.receipt.id)), [['c']], 'search reads items')
  assert.deepEqual(M.filedFolders([R1, R2, R3], { query: 'INV-206' }).map(f => f.key), ['September 2026'], 'and order numbers')
})

test('a folded slip says what it needs in a few words', () => {
  const chk = (checks, duplicate = null) => ({ checks, duplicate })
  assert.deepEqual(M.slipState(chk([{ key: 'split', tone: 'info' }]), 2), { tone: 'info', text: '2 rows · ready' })
  assert.deepEqual(M.slipState(chk([{ key: 'x', tone: 'warn' }]), 1), { tone: 'warn', text: '1 row · 1 warning' })
  assert.deepEqual(M.slipState(chk([{ key: 'rule:meals_documentation', tone: 'block' }]), 1), { tone: 'warn', text: 'Needs purpose and attendees' })
  assert.deepEqual(M.slipState(chk([{ key: 'not_started', tone: 'block', text: 'FY28 hasn’t started.' }]), 1), { tone: 'warn', text: 'Start FY28' })
  assert.deepEqual(M.slipState(chk([], { expense: { row_label: 'FY26 row 4' } }), 1), { tone: 'warn', text: 'Matches FY26 row 4' })
})

